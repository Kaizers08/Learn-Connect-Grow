# scripts/setup-clamav.ps1
#
# Installs ClamAV on this Windows machine so the scanner service (scanner/server.js)
# can talk to a local clamd daemon.
#
# What it does:
#   1. Downloads the official ClamAV Windows build
#   2. Extracts it to $InstallDir (default C:\ClamAV)
#   3. Creates a minimal clamd.conf (TCP 127.0.0.1:3310, private)
#   4. Runs freshclam once to download the virus database
#   5. Registers an hourly freshclam task (Task Scheduler) so signatures stay current
#
# Usage (from the project root):
#   .\scripts\setup-clamav.ps1
#   .\scripts\setup-clamav.ps1 -InstallDir "D:\Tools\ClamAV" -StartDaemon
#
# Notes:
#   - Run in a normal PowerShell window (no admin needed for the download/extract;
#     admin is only needed if you register the machine-wide scheduled task, which
#     this script does with -RegisterTask, default on for the current user).

[CmdletBinding()]
param(
    [string] $InstallDir = "C:\ClamAV",
    # Latest stable Windows build. Verify the current version at
    # https://www.clamav.net/downloads (or the GitHub releases page) before
    # bumping this.
    [string] $Version = "1.5.4",
    [string] $Arch = "x64",
    [ValidateSet('true', 'false')]
    [string] $RegisterHourlyFreshclam = "true",
    [switch] $StartDaemon
)

$ErrorActionPreference = "Stop"

# Official release assets. clamav.net redirects to a CDN that blocks plain
# Invoke-WebRequest, so use the GitHub release asset instead.
$ZipUrl = "https://github.com/Cisco-Talos/clamav/releases/download/clamav-$Version/clamav-$Version.win.$Arch.zip"
$ZipPath = Join-Path $env:TEMP "clamav-$Version.win.$Arch.zip"
$DatabaseDir = Join-Path $InstallDir "database"
$LogFile = Join-Path $InstallDir "clamd.log"

function Write-Step($message) {
    Write-Host "==> $message" -ForegroundColor Cyan
}

# -- 1. Download --------------------------------------------------------------
Write-Step "Downloading ClamAV $Version"
if (-not (Test-Path -LiteralPath $ZipPath)) {
    Invoke-WebRequest -Uri $ZipUrl -OutFile $ZipPath -UseBasicParsing
}
Write-Host "    downloaded to $ZipPath"

# -- 2. Extract ---------------------------------------------------------------
Write-Step "Extracting to $InstallDir"
New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
if (Test-Path -LiteralPath $ZipPath) {
    Expand-Archive -LiteralPath $ZipPath -DestinationPath $InstallDir -Force
}

# The zip may contain a versioned subfolder - flatten it if so.
$inner = Get-ChildItem -LiteralPath $InstallDir -Directory |
    Where-Object { $_.Name -like "clamav-*" } |
    Select-Object -First 1
if ($inner) {
    Get-ChildItem -LiteralPath $inner.FullName | ForEach-Object {
        Move-Item -LiteralPath $_.FullName -Destination (Join-Path $InstallDir $_.Name) -Force
    }
    Remove-Item -LiteralPath $inner.FullName -Recurse -Force
}

New-Item -ItemType Directory -Force -Path $DatabaseDir | Out-Null

$ClamScan = Join-Path $InstallDir "clamscan.exe"
$ClamD = Join-Path $InstallDir "clamd.exe"
$FreshClam = Join-Path $InstallDir "freshclam.exe"

foreach ($exe in @($ClamScan, $ClamD, $FreshClam)) {
    if (-not (Test-Path -LiteralPath $exe)) {
        throw "Expected $exe was not found. Check the contents of $InstallDir."
    }
}
Write-Host "    found clamscan.exe, clamd.exe and freshclam.exe"

# -- 3. clamd.conf ------------------------------------------------------------
# Kept deliberately small: loopback only (never expose the AV daemon to the
# network) and TCP is enabled so scanner/server.js can reach it.
$Conf = @"
# Minimal clamd config generated by scripts/setup-clamav.ps1
#
# Paths use FORWARD slashes on purpose: clamd rejects Windows backslash
# paths in these options with a bare "Malformed database" error.
LogFile $($LogFile -replace '\\', '/')
LogTime yes
LogRotate yes
DatabaseDirectory $($DatabaseDir -replace '\\', '/')
TCPSocket 3310
TCPAddr 127.0.0.1
MaxThreads 4
StreamMaxLength 64M
MaxScanSize 64M
MaxFileSize 64M
Foreground yes
"@

$ConfPath = Join-Path $InstallDir "clamd.conf"
Set-Content -LiteralPath $ConfPath -Value $Conf -Encoding ASCII
Write-Host "    wrote $ConfPath"

# -- 4. freshclam.conf --------------------------------------------------------
$FreshConf = @"
DatabaseDirectory $DatabaseDir
UpdateLogFile $(Join-Path $InstallDir "freshclam.log")
DatabaseMirror database.clamav.net
Checks 12
"@
Set-Content -LiteralPath (Join-Path $InstallDir "freshclam.conf") -Value $FreshConf -Encoding ASCII

Write-Step "Downloading virus signatures (freshclam) - this can take a few minutes"
& $FreshClam --config-file=(Join-Path $InstallDir "freshclam.conf")
if ($LASTEXITCODE -ne 0) {
    Write-Warning "freshclam exited with code $LASTEXITCODE. Re-run it later to finish the database download."
}
else {
    Write-Host "    signatures downloaded"
}

# -- 5. Hourly freshclam task -------------------------------------------------
if ($RegisterHourlyFreshclam -eq "true") {
    Write-Step "Registering hourly freshclam task"
    $action = New-ScheduledTaskAction -Execute $FreshClam `
        -Argument "--config-file=`"$InstallDir\freshclam.conf`"" `
        -WorkingDirectory $InstallDir
    $trigger = New-ScheduledTaskTrigger -Once -At (Get-Date).AddMinutes(5) `
        -RepetitionInterval (New-TimeSpan -Hours 1) `
        -RepetitionDuration (New-TimeSpan -Days 3650)
    $settings = New-ScheduledTaskSettingsSet -StartWhenAvailable -DontStopOnIdleEnd
    Register-ScheduledTask -TaskName "ClamAV freshclam (hourly)" -Action $action `
        -Trigger $trigger -Settings $settings -Force | Out-Null
    Write-Host "    registered task 'ClamAV freshclam (hourly)' for $env:USERNAME"
}

# -- 6. PATH + optional daemon start -------------------------------------------
$userPath = [Environment]::GetEnvironmentVariable("Path", "User")
if ($userPath -notlike "*$InstallDir*") {
    [Environment]::SetEnvironmentVariable("Path", "$InstallDir;$userPath", "User")
    Write-Host "    added $InstallDir to your user PATH (restart terminals to pick it up)"
}

Write-Step "ClamAV is installed"
& $ClamScan --version

if ($StartDaemon) {
    Write-Step "Starting clamd"
    Start-Process -FilePath $ClamD `
        -ArgumentList "--config-file=`"$ConfPath`"" `
        -WorkingDirectory $InstallDir -WindowStyle Hidden
    Start-Sleep -Seconds 3
    $ping = Test-NetConnection -ComputerName 127.0.0.1 -Port 3310 -InformationLevel Quiet
    if ($ping) {
        Write-Host "    clamd is listening on 127.0.0.1:3310" -ForegroundColor Green
    }
    else {
        Write-Warning "clamd did not open port 3310. Check $LogFile"
    }
}
else {
    Write-Host ""
    Write-Host "Next steps:" -ForegroundColor Yellow
    Write-Host "  1. Start the daemon:   & '$ClamD' --config-file '$ConfPath'"
    Write-Host "  2. Start the scanner:  cd scanner; npm install; npm start"
    Write-Host "  3. Test it:            curl http://localhost:3030/health"
}
